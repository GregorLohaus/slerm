#!/usr/bin/env bash
# Prints the Homebrew cask for a release, as published in the GregorLohaus/homebrew-tap repository:
#
#   scripts/homebrew-cask.sh 0.1.0 slerm-0.1.0-macos-arm64.zip > Casks/slerm.rb
#
# The release workflow runs this against the zip attached to the GitHub release and pushes the
# result to the tap, so edit the cask here, not there. REPO is the GitHub repository whose
# release holds the zip.
set -euo pipefail

VERSION=${1:?usage: homebrew-cask.sh VERSION ZIP}
ZIP=${2:?usage: homebrew-cask.sh VERSION ZIP}
REPO=${REPO:-GregorLohaus/slerm}
SHA256=$(shasum -a 256 "$ZIP" | cut -d' ' -f1)

cat <<CASK
# Generated by scripts/homebrew-cask.sh in $REPO; edit it there.
cask "slerm" do
  version "$VERSION"
  sha256 "$SHA256"

  url "https://github.com/$REPO/releases/download/v#{version}/slerm-#{version}-macos-arm64.zip"
  name "slerm"
  desc "Ghostty-powered terminal with tiled and floating panes"
  homepage "https://github.com/$REPO"

  livecheck do
    url :url
    strategy :github_latest
  end

  # Releases are built on Apple Silicon only (see .github/workflows/release.yml).
  depends_on arch: :arm64
  depends_on :macos

  app "slerm.app"
  binary "#{appdir}/slerm.app/Contents/MacOS/slerm"

  # Release builds are ad-hoc signed, not notarized: with the quarantine flag Homebrew sets,
  # Gatekeeper would block the app and the slerm command until approved in System Settings,
  # and again after every upgrade.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/slerm.app"], must_succeed: false
  end

  zap trash: "~/.config/slerm"
end
CASK
